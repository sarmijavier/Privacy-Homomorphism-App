from flask import Flask, render_template, request, send_file
import os
import json
from werkzeug.utils import secure_filename
import pandas as pd

# Import your server sum logic
from step2_server_sum import *

app = Flask(__name__)

UPLOAD_FOLDER = "uploads"
OUTPUT_FOLDER = "outputs"

os.makedirs(UPLOAD_FOLDER, exist_ok=True)
os.makedirs(OUTPUT_FOLDER, exist_ok=True)

@app.route("/")
def home():
    return render_template("Index2.html")


@app.route("/upload", methods=["POST"])
def upload():
    # Retrieve files from the request
    csv_file = request.files["file"]
    json_file = request.files["metadata"]

    csv_name = secure_filename(csv_file.filename)
    json_name = secure_filename(json_file.filename)

    csv_path = os.path.join(UPLOAD_FOLDER, csv_name)
    json_path = os.path.join(UPLOAD_FOLDER, json_name)

    # Save uploaded files
    csv_file.save(csv_path)
    json_file.save(json_path)
    
    # Output file generated by function
    output_csv = os.path.join(OUTPUT_FOLDER, "encrypted_results.csv")
    output_json = os.path.join(OUTPUT_FOLDER, "encrypted_results.json")

    # 1. Call function to process data
    server_stats(csv_path, json_path, output_csv, output_json)
    
    # 2. Read CSV output
    df = pd.read_csv(output_csv)
    
    columns = df.columns.tolist()
    encrypted_sums_strings = []

    for col in columns:
        # Cast to string safely, avoiding numeric parsing entirely
        raw_string = str(df[col].iloc[0])
        encrypted_sums_strings.append(raw_string)

    header = columns
    
    # 4. Build HTML table
    table_html = "<table><tr>"
    table_html += "".join(f"<th>{h}</th>" for h in header)
    table_html += "</tr><tr>"
    table_html += "".join(f"<td>{m}</td>" for m in encrypted_sums_strings)
    table_html += "</tr></table>"

    # 5. Return final HTML page
    return f"""
    <html>
    <head>
        <title>Results</title>
        <style>
            body {{
                font-family: Arial;
                background: #f3f4f6;
                padding: 40px;
            }}

            table {{
                width: 100%;
                border-collapse: collapse;
                margin-top: 20px;
                table-layout: fixed;
            }}
            th, td {{
                border: 1px solid #ddd;
                padding: 10px;
                text-align: center;
                overflow: hidden;
            }}
            th {{
                background: #2563eb;
                color: white;
            }}
            a.button {{
                display: inline-block;
                margin-top: 20px;
                padding: 10px 15px;
                background: #2563eb;
                color: white;
                text-decoration: none;
                border-radius: 8px;
            }}
        </style>
    </head>

    <body>
        <div class="container">

            <h1>Encripted Sums</h1>

            {table_html}

            <br><br>
            <a class="button" href="/download">
                Download CSV
            </a>

            <br><br>
            <a href="/">Upload another file</a>

        </div>
    </body>
    </html>
    """

@app.route("/download")
def download_file():
    # Provide the generated file for download
    output_file = os.path.join(OUTPUT_FOLDER, "encrypted_results.csv")
    return send_file(output_file, as_attachment=True)

if __name__ == "__main__":
    # Running on 5001 to avoid access denied errors on macOS
    app.run(debug=True, port=5001)